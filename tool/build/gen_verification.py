"""Embed results/tool_verification.csv and verification_references.json into tool/verification_data.js
so that the Validation tab shows the latest test run. Run after `npm test`."""
import csv, json, pathlib, datetime
root = pathlib.Path(__file__).resolve().parents[2]
rows = list(csv.DictReader(open(root / "results/tool_verification.csv", encoding="utf-8")))
for r in rows:
    for k in ("tool", "reference", "tolerance"):
        try: r[k] = float(r[k])
        except ValueError: pass
    r["pass"] = r["pass"] == "true"
out = {"generated": datetime.date.today().isoformat(), "n": len(rows), "passed": sum(r["pass"] for r in rows), "rows": rows}
(root / "tool/verification_data.js").write_text("// Generated by tool/build/gen_verification.py from results/tool_verification.csv. Do not edit.\nexport const VERIFICATION = " + json.dumps(out, ensure_ascii=False) + ";\n", encoding="utf-8")
print(out["n"], out["passed"])
